"""Regenerates geode_shim/geode.def.

Exports every Geode 5.11.2 symbol (geode_shim/geode_5_11_2_exports.txt) that
the shim's object files define. Build the shim first, then run:

  python tools/geode_shim/update_def.py --objects build/geode_shim/reode_geode_shim.dir/Debug

Symbols the compiler already exports through __declspec(dllexport)
(matjson, VersionInfo) are skipped, so nothing is exported twice.
"""

import argparse
import glob
import os
import re
import subprocess

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
DEF_HEADER = """; Copyright 2026 The Reode Authors
;
; Geode API symbols implemented by Reode's Geode.dll, by decorated name.
; Reode only loads a Geode mod when every symbol it imports is exported.
; GENERATED by tools/geode_shim/update_def.py; do not edit by hand.
LIBRARY Geode
EXPORTS
"""


def find_dumpbin():
    vswhere = os.path.expandvars(
        r'%ProgramFiles(x86)%\Microsoft Visual Studio\Installer\vswhere.exe')
    install = subprocess.check_output(
        [vswhere, '-latest', '-products', '*', '-property', 'installationPath'],
        text=True).strip()
    candidates = glob.glob(os.path.join(
        install, 'VC', 'Tools', 'MSVC', '*', 'bin', 'Hostx64', 'x64',
        'dumpbin.exe'))
    return sorted(candidates)[-1]


def defined_symbols(dumpbin, objects):
    symbols, exported = set(), set()
    pattern = re.compile(r'SECT\w+\s+\S+\s+(?:\(\)|notype)?\s*External\s+\|\s+(\S+)')
    for obj in objects:
        out = subprocess.run([dumpbin, '/nologo', '/symbols', obj],
                             capture_output=True, text=True).stdout
        symbols.update(pattern.findall(out))
        directives = subprocess.run([dumpbin, '/nologo', '/directives', obj],
                                    capture_output=True, text=True).stdout
        exported.update(re.findall(r'/EXPORT:([^\s,]+)', directives))
    return symbols, exported


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--objects', required=True)
    args = parser.parse_args()

    reference_path = os.path.join(ROOT, 'geode_shim', 'geode_5_11_2_exports.txt')
    with open(reference_path, encoding='utf-8') as stream:
        reference = {line.strip() for line in stream
                     if line.strip() and not line.startswith('#')}
    objects = glob.glob(os.path.join(args.objects, '*.obj'))
    symbols, exported = defined_symbols(find_dumpbin(), objects)
    names = sorted((reference & symbols) - exported)
    with open(os.path.join(ROOT, 'geode_shim', 'geode.def'), 'w',
              encoding='utf-8', newline='\n') as stream:
        stream.write(DEF_HEADER)
        stream.writelines(f'  {name}\n' for name in names)
    print(f'{len(names)} symbols in geode.def '
          f'({len(reference & (symbols | exported))} of {len(reference)} '
          'Geode 5.11.2 exports implemented)')


if __name__ == '__main__':
    main()
